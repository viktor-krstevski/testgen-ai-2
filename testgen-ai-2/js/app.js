function selectModel(element, model) {
    // Remove active class from all model cards
    document.querySelectorAll('.model-card').forEach(card => {
        card.classList.remove('active');
        const icon = card.querySelector('.bi');
        icon.className = 'bi bi-circle';
        icon.style.color = 'var(--border-color)';
    });

    // Add active to selected card
    element.classList.add('active');
    const icon = element.querySelector('.bi');
    icon.className = 'bi bi-check-circle-fill text-success';

    // Update current model
    currentModel = model;
    console.log('Selected model:', model);
}

