// ===================================
// History Management
// ===================================
function addToHistory(instructions, model, framework, code) {
    const now = new Date();
    const timestamp = now.toLocaleString('mk-MK', {
        day: '2-digit',
        month: '2-digit',
        year: 'numeric',
        hour: '2-digit',
        minute: '2-digit'
    });
    
    const historyItem = {
        id: Date.now(),
        title: generateTestTitle(instructions),
        instructions: instructions,
        model: model,
        framework: framework,
        code: code,
        timestamp: timestamp
    };
    
    testHistory.unshift(historyItem);
    
    // Keep only last 20 items
    if (testHistory.length > 20) {
        testHistory = testHistory.slice(0, 20);
    }
    
    // Update history display if on history page
    updateHistoryDisplay();
}

function generateTestTitle(instructions) {
    // Generate a short title from instructions
    const words = instructions.split(' ').slice(0, 4);
    return words.join(' ') + (instructions.split(' ').length > 4 ? '...' : '');
}

function updateHistoryDisplay() {
    const container = document.getElementById('history-container');
    if (!container) return;
    
    if (testHistory.length === 0) {
        container.innerHTML = `
            <div class="text-center text-secondary py-5">
                <i class="bi bi-inbox" style="font-size: 3rem;"></i>
                <p class="mt-3">Немате генерирани тестови сеуште</p>
            </div>
        `;
        return;
    }
    
    container.innerHTML = testHistory.map(item => `
        <div class="history-item">
            <div class="d-flex justify-content-between align-items-start">
                <div>
                    <h5>${escapeHtml(item.title)}</h5>
                    <p class="text-secondary mb-2">${escapeHtml(item.instructions.substring(0, 100))}${item.instructions.length > 100 ? '...' : ''}</p>
                    <span class="model-badge ${item.model}">${getModelDisplayName(item.model)}</span>
                    <span class="badge badge-custom">${item.framework === 'selenium' ? 'Selenium' : 'Playwright'}</span>
                </div>
                <div class="text-end">
                    <small class="text-secondary">${item.timestamp}</small>
                    <div class="mt-2">
                        <button class="btn btn-sm copy-btn" onclick="viewHistoryItem(${item.id})">
                            <i class="bi bi-eye"></i> Прегледај
                        </button>
                    </div>
                </div>
            </div>
        </div>
    `).join('');
}

function viewHistoryItem(id) {
    const item = testHistory.find(h => h.id === id);
    if (!item) return;
    
    // Switch to generator page
    showPage('generator');
    
    // Fill in the data
    document.getElementById('test-instructions').value = item.instructions;
    document.getElementById('code-output').innerHTML = `<pre><code class="text-light">${escapeHtml(item.code)}</code></pre>`;
}

function getModelDisplayName(model) {
    const names = {
        'gpt': 'GPT-4',
        'gpt4': 'GPT-4',
        'claude': 'Claude',
        'gemini': 'Gemini'
    };
    return names[model] || model.toUpperCase();
}

// ===================================
// Utility Functions
// ===================================
function escapeHtml(text) {
    const div = document.createElement('div');
    div.textContent = text;
    return div.innerHTML;
}

