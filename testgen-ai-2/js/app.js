function downloadCode(format) {
    const codeElement = document.querySelector('#code-output pre code');
    if (!codeElement) {
        alert('Нема генериран код за преземање!');
        return;
    }
    
    const code = codeElement.textContent;
    const extension = currentFramework === 'selenium' ? 'py' : 'js';
    const filename = `test_${Date.now()}.${extension}`;
    
    const blob = new Blob([code], { type: 'text/plain' });
    const url = window.URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = filename;
    a.click();
    window.URL.revokeObjectURL(url);
}

